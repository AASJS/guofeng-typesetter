#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
validate_card.py — Guofeng Typesetter 产物合规校验
灵感来自 isjiamu/gzh-design-skill 的「双关卡校验」：把平台限制/排版红线交给脚本确定性检查，不靠模型记忆。

用法：
  python3 validate_card.py <file.html>            # 普通浏览器单文件模式
  python3 validate_card.py --wechat <file.html>   # 公众号内嵌模式（全内联）

退出码：0 = 通过；1 = 存在 ERROR。
"""
import argparse
import re
import sys

# 全局排版红线（跨系统混色禁止、落款统一）
SIGNATURE = "静心知识库"
FORBIDDEN_WATERMARK = ["AI生成", "ai-generated", "Generated by AI"]

# 公众号平台会过滤的写法（参考 doocs/md、mdnice、wechat-format、gzh-design）
WECHAT_FORBIDDEN_PATTERNS = {
    "<style": "禁止使用 <style> 标签（公众号会过滤）",
    "class=": "禁止使用 class 属性（改用内联 style）",
    "display:grid": "禁止使用 display:grid（公众号不支持）",
    "display: grid": "禁止使用 display:grid（公众号不支持）",
    "position:absolute": "禁止使用 position:absolute",
    "position:fixed": "禁止使用 position:fixed",
    "position: absolute": "禁止使用 position:absolute",
    "position: fixed": "禁止使用 position:fixed",
    "@media": "禁止使用 @media 媒体查询",
    "@keyframes": "禁止使用 @keyframes 动画",
    "var(--": "禁止使用 CSS 变量（公众号不支持）",
    "<script": "禁止使用 <script> 标签",
    "@import": "禁止 @import 外部样式",
}


def find_all(patterns, text):
    """返回 (pattern, count) 列表，仅统计命中的。"""
    hits = []
    for p, msg in patterns.items():
        n = len(re.findall(re.escape(p), text, re.IGNORECASE))
        if n:
            hits.append((p, n, msg))
    return hits


def check_normal(path):
    errors, warns = [], []
    try:
        with open(path, encoding="utf-8") as f:
            html = f.read()
    except Exception as e:
        print(f"ERROR  无法读取文件：{e}")
        return 1, 0

    if not html.lstrip().lower().startswith("<!doctype html"):
        errors.append("缺少 <!DOCTYPE html> 声明，非标准单文件 HTML")
    if "<html" not in html.lower():
        errors.append("缺少 <html> 根元素")

    # 必须有标题或主标题
    if not (re.search(r"<title>", html, re.I) or re.search(r"<h1", html, re.I)):
        errors.append("缺少 <title> 或 <h1> 主标题")

    # 落款统一
    if SIGNATURE not in html:
        errors.append(f"缺失统一落款「{SIGNATURE} · @圣为Ai设计」")

    # 禁止 AI 水印
    for w in FORBIDDEN_WATERMARK:
        if w.lower() in html.lower():
            errors.append(f"出现禁止的 AI 水印字样：{w}")

    # 字体 CDN 建议（非强制）
    if "fonts" not in html and "font-family" not in html:
        warns.append("未检测到字体引入（font-family / CDN），可能使用系统默认字体")

    # 排版基线软检查：是否设置了行高与字距
    if "line-height" not in html:
        warns.append("未检测到 line-height，建议按垂直韵律设置行高")
    if "font-feature-settings" not in html and "text-rendering" not in html:
        warns.append("未设置 text-rendering / font-feature-settings，文字渲染质感可提升")

    return report("普通单文件模式", errors, warns)


def check_wechat(path):
    errors, warns = [], []
    try:
        with open(path, encoding="utf-8") as f:
            html = f.read()
    except Exception as e:
        print(f"ERROR  无法读取文件：{e}")
        return 1, 0

    hits = find_all(WECHAT_FORBIDDEN_PATTERNS, html)
    for p, n, msg in hits:
        errors.append(f"{msg}（命中 {n} 次）")

    # 公众号要求文字尽量用 span 包裹（松检查：正文是否直接裸文本）
    naked = re.findall(r">([^<>\n]{6,})<", html)
    if len(naked) > 3:
        warns.append(f"发现 {len(naked)} 处可能未用 <span> 包裹的裸文本，粘贴后样式可能不稳固")

    if SIGNATURE not in html:
        errors.append(f"缺失统一落款「{SIGNATURE} · @圣为Ai设计」")

    return report("公众号内嵌模式", errors, warns)


def report(mode, errors, warns):
    print(f"\n=== Guofeng Typesetter 校验 · {mode} ===")
    if errors:
        print(f"\n[ERROR] {len(errors)} 个问题（必须修复）：")
        for e in errors:
            print(f"  ✗ {e}")
    else:
        print("\n[ERROR] 0 个 —— 通过。")
    if warns:
        print(f"\n[WARN] {len(warns)} 个建议：")
        for w in warns:
            print(f"  ! {w}")
    print()
    return (1 if errors else 0), len(warns)


def main():
    ap = argparse.ArgumentParser(description="Guofeng Typesetter 产物合规校验")
    ap.add_argument("file", help="待校验的 HTML 文件")
    ap.add_argument("--wechat", action="store_true", help="公众号内嵌模式（全内联）校验")
    args = ap.parse_args()

    if args.wechat:
        code, _ = check_wechat(args.file)
    else:
        code, _ = check_normal(args.file)
    sys.exit(code)


if __name__ == "__main__":
    main()
